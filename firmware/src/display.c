void lcd_text(uint16_t x, uint16_t y, const char *s, uint16_t fg, uint16_t bg){
    while(*s){
        if(*s>=' ' && *s<='~'){
            const uint8_t *g=font5x7[*s-' '];
            for(int c=0;c<5;c++) for(int r=0;r<7;r++)
                lcd_draw_pixel(x+c, y+r, (g[c]>>r)&1 ? fg : bg);
        }
        x+=6; s++;
    }
}
