/* Bus 8080 del RT-950 Pro (Hertzz58, verificado en ese radio;
 * en el 1000Pro CANDIDATO): datos PD8-PD15, WR=PD0, CS=PD1,
 * RST=PD2, DC=PD3, backlight PC6 + PB3 secundario. */
static void lcd_bus_write(uint8_t b){
    uint32_t odr = GPIOD->ODR;
    odr &= ~(0xFFu<<8); odr |= ((uint32_t)b<<8);
    GPIOD->ODR = odr;
    gpio_clr(GPIOD,0); /* WR bajo */
    for(volatile int i=0;i<10;i++){ }
    gpio_set(GPIOD,0); /* WR alto */
}
static void lcd_write_cmd(uint8_t c){
    gpio_clr(GPIOD,3); /* DC=cmd */
    gpio_clr(GPIOD,1); /* CS assert */
    lcd_bus_write(c);
    gpio_set(GPIOD,1);
}
static void lcd_write_data(uint8_t d){
    gpio_set(GPIOD,3); /* DC=data */
    gpio_clr(GPIOD,1);
    lcd_bus_write(d);
    gpio_set(GPIOD,1);
}
void lcd_init(void){
    for(int i=0;i<16;i++) gpio_mode_out(GPIOD,(uint32_t)i);
    gpio_mode_out(GPIOC,6); gpio_mode_out(GPIOB,3);
    gpio_set(GPIOD,2); hal_delay_ms(10);
    gpio_clr(GPIOD,2); hal_delay_ms(10);
    gpio_set(GPIOD,2); hal_delay_ms(120);
    lcd_write_cmd(0x01); hal_delay_ms(120); /* SWRESET */
    lcd_write_cmd(0x11); hal_delay_ms(120); /* SLPOUT */
    lcd_write_cmd(0x3A); lcd_write_data(0x55); /* COLMOD 16bpp */
    lcd_write_cmd(0x36); lcd_write_data(0x00); /* MADCTL */
    lcd_write_cmd(0x29); /* DISPON */
    gpio_set(GPIOC,6); gpio_set(GPIOB,3); /* backlight on */
}
void lcd_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1){
    lcd_write_cmd(0x2A); lcd_write_data(x0>>8); lcd_write_data(x0); lcd_write_data(x1>>8); lcd_write_data(x1);
    lcd_write_cmd(0x2B); lcd_write_data(y0>>8); lcd_write_data(y0); lcd_write_data(y1>>8); lcd_write_data(y1);
    lcd_write_cmd(0x2C);
}
void lcd_fill(uint16_t color){
    lcd_set_window(0,0,LCD_W-1,LCD_H-1);
    for(uint32_t i=0;i<(uint32_t)LCD_W*LCD_H;i++){ lcd_write_data(color>>8); lcd_write_data(color&0xFF); }
}
void lcd_draw_pixel(uint16_t x, uint16_t y, uint16_t color){
    if(x>=LCD_W||y>=LCD_H) return;
    lcd_set_window(x,y,x,y); lcd_write_data(color>>8); lcd_write_data(color&0xFF);
}
void lcd_color_bars(void){
    static const uint16_t bars[8]={LCD_RED,LCD_GREEN,LCD_BLUE,LCD_WHITE,0xFFE0,0xF81F,0x07FF,LCD_BLACK};
    for(int i=0;i<8;i++){ lcd_set_window(i*30,0,i*30+29,LCD_H-1); for(uint32_t p=0;p<30u*LCD_H;p++){ lcd_write_data(bars[i]>>8); lcd_write_data(bars[i]&0xFF); } }
}
